from datetime import datetime
from enum import Enum
from typing import Any, Optional
from uuid import UUID

from pydantic import BaseModel, Field


# ---------- enums ----------
class Category(str, Enum):
    medical = "medical"
    rescue = "rescue"
    food = "food"
    water = "water"
    shelter = "shelter"
    other = "other"  # not an emergency / unclear: needs human review


class ReportStatus(str, Enum):
    processing = "processing"
    triaged = "triaged"
    failed = "failed"


class CaseStatus(str, Enum):
    open = "open"
    assigned = "assigned"
    resolved = "resolved"


class TriageSource(str, Enum):
    gemma = "gemma"
    fallback = "fallback"


class ResourceType(str, Enum):
    food = "food"
    water = "water"
    medicine = "medicine"
    transport = "transport"
    shelter = "shelter"


# ---------- reports ----------
class GPS(BaseModel):
    lat: float = Field(ge=-90, le=90)
    lng: float = Field(ge=-180, le=180)


class ReportIn(BaseModel):
    id: UUID = Field(description="Generated by the app. Same id = same report (idempotent).")
    raw_text: str = Field(min_length=1, max_length=2000)
    lang_hint: Optional[str] = Field(default=None, max_length=10)
    client_created_at: Optional[datetime] = None
    gps: Optional[GPS] = None


class Triage(BaseModel):
    severity: int = Field(ge=1, le=5)
    category: Category
    people_affected: int = Field(ge=0, default=1)
    location_text: str = ""
    needs: list[str] = []
    language_detected: str = "und"
    summary_english: str = ""
    suggested_action: str = ""


class ReportOut(BaseModel):
    id: UUID
    raw_text: str
    lang_hint: Optional[str] = None
    gps: Optional[GPS] = None
    client_created_at: Optional[datetime] = None
    received_at: datetime
    updated_at: datetime
    status: ReportStatus
    triage_source: Optional[TriageSource] = None
    case_status: CaseStatus = CaseStatus.open
    triage: Optional[Triage] = Field(default=None, description="null while status=processing")


class SubmitAck(BaseModel):
    id: UUID
    status: ReportStatus
    received_at: datetime


class BatchIn(BaseModel):
    reports: list[dict[str, Any]] = Field(
        max_length=100, description="Each item has the same shape as ReportIn. Validated per item."
    )


class BatchItemResult(BaseModel):
    id: Optional[str] = None
    result: str = Field(description="created | duplicate | rejected")
    error: Optional[str] = None


class BatchOut(BaseModel):
    results: list[BatchItemResult]


class ReportList(BaseModel):
    server_time: datetime = Field(description="Send back as ?since= on the next poll")
    items: list[ReportOut]


class CaseUpdate(BaseModel):
    case_status: CaseStatus


# ---------- resources ----------
class ResourceIn(BaseModel):
    id: UUID
    type: ResourceType
    quantity: int = Field(ge=1)
    unit: str = ""
    location_text: str = ""
    contact: str = ""
    available_until: Optional[datetime] = None


class ResourceOut(ResourceIn):
    status: str = "available"  # available | allocated
    received_at: datetime


# ---------- matches / locations ----------
class MatchOut(BaseModel):
    id: UUID
    report_id: UUID
    resource_id: UUID
    rank: int = 1
    reason: str = ""
    source: str = "rule"  # gemma | rule
    status: str = "suggested"  # suggested | accepted | rejected


class LocationOut(BaseModel):
    id: str
    name: str
    type: str  # hospital | shelter | camp | safe_zone
    lat: float
    lng: float


class Health(BaseModel):
    status: str
    version: str
    server_time: datetime
    mongo: str
    ollama: str
    queue_depth: int


# ---------- AI server settings (additive; admin only) ----------
class AIServerIn(BaseModel):
    base_url: Optional[str] = Field(default=None, description="e.g. http://192.168.137.12:11434")
    model: Optional[str] = None


class AIServerOut(BaseModel):
    base_url: str
    model: str
    status: str  # unknown | online | offline | model_missing
    detail: str = ""